// Collects every MaterialCommunityIcons name used in the source (including
// names chosen dynamically from string literals) and emits a tree-shaken map.
import fs from 'node:fs';
import path from 'node:path';
import * as mdi from '@mdi/js';
const camel = (n) => 'mdi' + n.split('-').map((p) => p[0].toUpperCase() + p.slice(1)).join('');
const found = new Map();
const walk = (d) => fs.readdirSync(d).forEach((f) => {
  const p = path.join(d, f);
  if (fs.statSync(p).isDirectory()) return walk(p);
  if (!/\.(jsx?|tsx?)$/.test(f)) return;
  for (const m of fs.readFileSync(p, 'utf8').matchAll(/['"`]([a-z0-9]+(?:-[a-z0-9]+)*)['"`]/g)) {
    const k = camel(m[1]);
    if (mdi[k]) found.set(m[1], mdi[k]);
  }
});
walk('src');
const body = [...found].sort().map(([n, d]) => `  '${n}': '${d}',`).join('\n');
fs.writeFileSync('src/web/icons.generated.js', `// AUTO-GENERATED by tools/gen-icons.mjs — Material Design Icons (Apache 2.0)\nexport default {\n${body}\n};\n`);
console.log('icons:', found.size);
